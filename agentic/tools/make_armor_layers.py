"""Writes TCArmorLayers.java: the layer definitions of TC4's custom armour models, both variants of each (f = 0.5 for helmets and leggings,
f = 1.0 for chestplates), converted by port_model.py."""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
GEAR = os.path.join(ROOT, 'original', 'decompiled', 'thaumcraft', 'client', 'renderers', 'models', 'gear')
OUT = os.path.join(ROOT, 'src', 'client', 'java', 'dev', 'neothaum', 'client', 'render', 'armor', 'TCArmorLayers.java')

MODELS = [('robe', 'ModelRobe'), ('knight', 'ModelKnightArmor'), ('leader', 'ModelLeaderArmor'), ('fortress', 'ModelFortressArmor')]

methods = []
for name, model in MODELS:
    for f, suffix in ((0.5, 'Small'), (1.0, 'Large')):
        gen = subprocess.run([sys.executable, os.path.join(HERE, 'port_model.py'), os.path.join(GEAR, model + '.java'), str(f)], capture_output=True,
            text=True, check=True).stdout
        body = gen[gen.index('\tpublic static LayerDefinition createLayer()'):].rstrip()
        body = body.replace('createLayer()', name + suffix + '()', 1)
        methods.append('\t/** %s(%sF). */\n%s' % (model, f, body))

java = '''package dev.neothaum.client.render.armor;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * TC4's custom armour models, generated by agentic/tools/make_armor_layers.py from the decompiled ModelRobe, ModelKnightArmor,
 * ModelLeaderArmor and ModelFortressArmor. Each hangs its parts off empty head, body, arm and leg parts named and placed as the vanilla
 * biped's, so the wearer's pose can be copied onto them. Do not edit by hand: change the generator.
 */
@SuppressWarnings("unused")
public final class TCArmorLayers {
%s

	private TCArmorLayers() {
	}
}
''' % '\n\n'.join(methods)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8').write(java)
print('wrote', OUT, len(methods), 'layers')
